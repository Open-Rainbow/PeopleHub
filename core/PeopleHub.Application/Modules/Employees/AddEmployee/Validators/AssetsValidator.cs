using FluentValidation;
using PeopleHub.Application.Modules.Employees.AddEmployee.Contracts;

namespace PeopleHub.Application.Modules.Employees.AddEmployee.Validators;

internal sealed class AssetsRequestValidator : AbstractValidator<AssetsRequest>
{
    public AssetsRequestValidator()
    {
        RuleFor(x => x.EmployeeId).NotEmpty().MaximumLength(50);
        RuleForEach(x => x.SystemAccess).SetValidator(new SystemAccessItemValidator());
        RuleForEach(x => x.Assets).SetValidator(new AssetItemValidator());
    }
}

internal sealed class SystemAccessItemValidator : AbstractValidator<SystemAccessItem>
{
    public SystemAccessItemValidator()
    {
        RuleFor(x => x.ApplicationOrSystemName).NotEmpty().MaximumLength(150);
        RuleFor(x => x.UsernameOrLoginId).NotEmpty().MaximumLength(100);
        RuleFor(x => x.RoleOrAccessProfile).MaximumLength(100);
        RuleFor(x => x.AccountStatus).MaximumLength(50);
        RuleFor(x => x.AccessApprovalReference).MaximumLength(100);
        RuleFor(x => x.AccessEndDate)
            .Must((x, v) => v >= x.AccessStartDate)
            .When(x => x.AccessStartDate.HasValue && x.AccessEndDate.HasValue)
            .WithMessage("Access end date must be on or after access start date.");
    }
}

internal sealed class AssetItemValidator : AbstractValidator<AssetItem>
{
    public AssetItemValidator()
    {
        // AssetAssignmentId is generated by the server, so it is not required.
        RuleFor(x => x.AssetAssignmentId).MaximumLength(50);
        RuleFor(x => x.AssetType).NotEmpty().MaximumLength(50);
        RuleFor(x => x.AssetCategory).MaximumLength(50);
        RuleFor(x => x.AssetName).NotEmpty().MaximumLength(150);
        RuleFor(x => x.AssetSerialNumber).MaximumLength(100);
        RuleFor(x => x.MakeBrand).MaximumLength(100);
        RuleFor(x => x.Model).MaximumLength(100);
        RuleFor(x => x.ConfigurationDetails).MaximumLength(1000);
        RuleFor(x => x.TagNumber).MaximumLength(100);
        RuleFor(x => x.OwnershipType).MaximumLength(50);
        RuleFor(x => x.IssuedDate).NotNull();
        RuleFor(x => x.IssuedBy).MaximumLength(150);
        RuleFor(x => x.IssueLocation).MaximumLength(150);
        RuleFor(x => x.AssetConditionAtIssue).MaximumLength(50);
        RuleFor(x => x.AssetValue).Must(v => v is null or >= 0).WithMessage("'{PropertyName}' cannot be negative.");
        RuleFor(x => x.DepositAmount).Must(v => v is null or >= 0).WithMessage("'{PropertyName}' cannot be negative.");
        RuleFor(x => x.DepositAmount)
            .NotNull()
            .When(x => x.SecurityDepositApplicable)
            .WithMessage("Deposit amount is required when a security deposit applies.");
        RuleFor(x => x.AssetRemarks).MaximumLength(500);
        RuleFor(x => x.AcknowledgementDate)
            .NotNull()
            .When(x => x.EmployeeAcknowledgement)
            .WithMessage("Acknowledgement date is required once the employee acknowledges.");
        RuleFor(x => x.WarrantyEndDate)
            .Must((x, v) => v >= x.WarrantyStartDate)
            .When(x => x.WarrantyStartDate.HasValue && x.WarrantyEndDate.HasValue)
            .WithMessage("Warranty end date must be on or after warranty start date.");
    }
}
