export const UI_ICON_FALLBACK: LucideIconData = CircleHelp;

const warned = new Set<string>();

export function resolveUiIcon(name: string | null | undefined): LucideIconData {
  const key = (name ?? '').trim();
  const icon = UI_ICONS[key];
  if (icon) {
    return icon;
  }
  if (key && !warned.has(key)) {
    warned.add(key);
    console.warn(`[ui-icon] Unknown icon "${key}". Add it to UI_ICONS in ui/icon-registry.ts.`);
  }
  return UI_ICON_FALLBACK;
}
